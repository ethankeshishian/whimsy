class FakeOp:
    """1Password with vaults and documents, in memory."""

    def __init__(self, vaults=("Shared Family", "Private")):
        self.vaults = list(vaults)
        self.docs = {}  # (vault, title) -> bytes
        self.calls = []

    def __call__(self, *args, timeout=120, binary=False, input=None):
        self.calls.append(args)
        if args[:2] == ("vault", "list"):
            return json.dumps([{"id": f"id-{v}", "name": v} for v in self.vaults])
        if args[:2] == ("document", "get"):
            title, vault = args[2], args[args.index("--vault") + 1]
            if (vault, title) not in self.docs:
                raise RuntimeError(f'"{title}" isn\'t an item in the "{vault}" vault')
            return self.docs[(vault, title)]
        if args[:2] == ("document", "create"):
            vault = args[args.index("--vault") + 1]
            title = args[args.index("--title") + 1]
            with open(args[2], "rb") as f:
                self.docs[(vault, title)] = f.read()
            return ""
        if args[:2] == ("item", "list"):
            return json.dumps([{"title": t, "vault": {"id": f"id-{v}", "name": v}} for v, t in self.docs])
        raise AssertionError(f"unexpected op call {args}")


class Vault(Base):
    def setUp(self):
        super().setUp()
        self.op = FakeOp()
        self.patch(sb, "op", self.op)
        self.patch(sb, "PUBLISH_JSON", os.path.join(self.tmp, "publish.json"))

    def write_config(self, vault):
        with open(sb.PUBLISH_JSON, "w") as f:
            json.dump({"signing_vault": vault}, f)

    def test_no_vault_configured_refuses(self):
        self.write_config("")
        with self.assertRaises(RuntimeError) as e:
            sb.configured_vault()
        self.assertIn("signing_vault", str(e.exception))

    def test_never_the_first_vault_listed(self):
        self.write_config("Private")
        self.assertEqual(sb.check_vault(sb.configured_vault()), "Private")
        self.write_config("Personal")
        with self.assertRaises(RuntimeError):
            sb.check_vault(sb.configured_vault())  # doesn't fall back to "Shared Family"

    def test_key_is_read_from_the_configured_vault_only(self):
        self.write_config("Private")
        self.op.docs[("Shared Family", sb.TITLE)] = b"planted"
        with self.assertRaises(RuntimeError):
            sb.signing_key()
        self.op.docs[("Private", sb.TITLE)] = b"the key"
        self.assertEqual(sb.signing_key(), b"the key")
        self.assertTrue(all("--vault" in call for call in self.op.calls if call[:2] == ("document", "get")))


class LegacyKeyFallback(Base):
    """Until the user migrates the key into 1Password (no signing_vault yet),
    publishing signs with the old on-disk key and warns, so `npm run ship`
    keeps publishing to Dev. Once a vault is configured it's the only source."""

    def setUp(self):
        super().setUp()
        self.op = FakeOp()
        self.patch(sb, "op", self.op)
        self.patch(sb, "PUBLISH_JSON", os.path.join(self.tmp, "publish.json"))
        self.patch(sb, "SIGNING", os.path.join(self.tmp, "signing"))
        self.patch(sb, "LEGACY_KEY", os.path.join(self.tmp, "signing", "private_key.pem"))
        # A fake PEM, built by concatenation so it never looks like a real key.
        self.pem = b"-----BEGIN " + b"PRIVATE KEY-----\nZmFrZQ==\n-----END " + b"PRIVATE KEY-----\n"

    def write_config(self, vault):
        with open(sb.PUBLISH_JSON, "w") as f:
            json.dump({"signing_vault": vault}, f)

    def write_legacy(self):
        os.makedirs(sb.SIGNING)
        with open(sb.LEGACY_KEY, "wb") as f:
            f.write(self.pem)

    def test_no_vault_uses_the_on_disk_key_with_a_warning(self):
        self.write_config("")
        self.write_legacy()
        self.assertEqual(sb.key_source(), ("legacy", sb.LEGACY_KEY))
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            self.assertEqual(sb.signing_key(), self.pem)
        self.assertIn("WARNING", err.getvalue())
        self.assertIn("signing_migrate.py", err.getvalue())
        self.assertNotIn("ZmFrZQ", err.getvalue())  # never the key itself
        self.assertNotIn("PRIVATE KEY", err.getvalue())
        self.assertEqual(self.op.calls, [])  # 1Password isn't needed yet

    def test_a_configured_vault_never_falls_back_to_disk(self):
        self.write_config("Private")
        self.write_legacy()
        self.assertEqual(sb.key_source(), ("vault", "Private"))
        with self.assertRaises(RuntimeError):
            sb.signing_key()  # not in the vault: refuse, don't read the disk copy
        self.op.docs[("Private", sb.TITLE)] = b"vault key"
        self.assertEqual(sb.signing_key(), b"vault key")

    def test_neither_refuses_with_the_vault_hint(self):
        self.write_config("")
        with self.assertRaises(RuntimeError) as e:
            sb.key_source()
        self.assertIn("signing_vault", str(e.exception))

    def test_dev_publish_gets_past_the_signing_check_without_a_vault(self):
        self.write_config("")
        self.write_legacy()
        reached = []

        def objdir():
            reached.append(True)
            raise RuntimeError("stop here: packaging isn't part of this test")
        self.patch(publish, "objdir", objdir)
        self.patch(sys, "argv", ["publish.py", "--channel", "dev"])
        with self.assertRaises(RuntimeError):
            publish.main()
        self.assertEqual(reached, [True])

    def test_dev_publish_without_vault_or_key_fails_before_packaging(self):
        self.write_config("")
        self.patch(publish, "objdir", lambda: self.fail("must fail before packaging"))
        self.patch(sys, "argv", ["publish.py", "--channel", "dev"])
        with self.assertRaises(SystemExit) as e:
            publish.main()
        self.assertIn("signing_vault", str(e.exception))


class TempFolders(Base):
    def setUp(self):
        super().setUp()
        self.patch(sb, "SCRATCH", os.path.join(self.tmp, "scratch"))

    def test_wiped_on_error(self):
        with self.assertRaises(ValueError):
            with sb.private_dir() as d:
                sb.write_private(os.path.join(d, "key"), b"secret")
                self.assertEqual(os.stat(d).st_mode & 0o777, 0o700)
                self.assertEqual(os.stat(os.path.join(d, "key")).st_mode & 0o777, 0o600)
                raise ValueError
        self.assertEqual(os.listdir(sb.SCRATCH), [])

    def test_leftovers_from_a_killed_run_are_swept(self):
        os.makedirs(os.path.join(sb.SCRATCH, "sign-old", "nssdb"))
        with open(os.path.join(sb.SCRATCH, "sign-old", "nssdb", "key4.db"), "wb") as f:
            f.write(b"x" * 100)
        with sb.private_dir() as d:
            self.assertEqual(os.listdir(sb.SCRATCH), [os.path.basename(d)])
        self.assertEqual(os.listdir(sb.SCRATCH), [])


@unittest.skipUnless(HAVE_TOOLS, "needs openssl, NSS's certutil/pk12util and a built signmar/mar")
class SignForReal(Base):
    """The real tools (openssl, certutil, pk12util, signmar) with a throwaway
    key: what publish.py runs, minus 1Password."""

    def setUp(self):
        super().setUp()
        self.key, self.der = self.throwaway_key()
        self.patch(sb, "SCRATCH", os.path.join(self.tmp, "scratch"))
        self.patch(sb, "signing_key", lambda: self.key)
        self.patch(publish, "PUBLIC_DER", self.der)
        self.passwords = iter(["a" * 48, "b" * 48])
        self.patch(publish.secrets, "token_hex", lambda n: next(self.passwords))
        self.commands = []
        real_run = publish.run

        def run(cmd, **kw):
            self.commands.append(list(cmd) if not isinstance(cmd, str) else [cmd])
            return real_run(cmd, **kw)
        self.patch(publish, "run", run)
        payload = os.path.join(self.tmp, "payload")
        os.makedirs(payload)
        with open(os.path.join(payload, "hello.txt"), "w") as f:
            f.write("hello\n")
        self.unsigned = os.path.join(self.tmp, "unsigned.mar")
        subprocess.run([MAR, "-H", "whimsy-release", "-V", "20261031.033000", "-C", payload, "-c",
                        self.unsigned, "hello.txt"], check=True, capture_output=True)

    def sign(self, unsigned, out):
        printed = io.StringIO()
        with contextlib.redirect_stdout(printed):
            publish.sign_mar(OBJ, unsigned, out)
        return printed.getvalue()

    def test_signs_verifies_and_leaves_nothing(self):
        out = os.path.join(self.tmp, "signed.mar")
        printed = self.sign(self.unsigned, out)
        env = dict(os.environ, DYLD_LIBRARY_PATH=os.path.join(OBJ, "dist", "bin"))
        verify = subprocess.run([SIGNMAR, "-D", self.der, "-v", out], env=env, capture_output=True)
        self.assertEqual(verify.returncode, 0, verify.stderr)
        info = subprocess.run([MAR, "-T", out], capture_output=True, text=True).stdout
        self.assertIn("whimsy-release", info)
        self.assertIn("20261031.033000", info)
        self.assertEqual(os.listdir(sb.SCRATCH), [])
        for secret in ("a" * 48, "b" * 48):
            self.assertNotIn(secret, printed)
            self.assertFalse(any(secret in arg for cmd in self.commands for arg in cmd))
        self.assertNotIn("BEGIN PRIVATE KEY", printed)
        self.assertNotIn("--empty-password", " ".join(" ".join(c) for c in self.commands))

    def test_a_failed_signing_leaves_nothing(self):
        with self.assertRaises(subprocess.CalledProcessError):
            self.sign(os.path.join(self.tmp, "missing.mar"), os.path.join(self.tmp, "out.mar"))
        self.assertEqual(os.listdir(sb.SCRATCH), [])

    def test_wrong_key_fails_verification(self):
        out = os.path.join(self.tmp, "signed.mar")
        self.sign(self.unsigned, out)
        _, other_der = self.throwaway_key()
        env = dict(os.environ, DYLD_LIBRARY_PATH=os.path.join(OBJ, "dist", "bin"))
        verify = subprocess.run([SIGNMAR, "-D", other_der, "-v", out], env=env, capture_output=True)
        self.assertNotEqual(verify.returncode, 0)


class Migrate(Base):
    def setUp(self):
        super().setUp()
        self.op = FakeOp()
        self.patch(sb, "op", self.op)
        self.patch(sb, "LEGACY_KEY", os.path.join(self.tmp, "signing", "private_key.pem"))
        self.patch(sb, "LEGACY_MARKER", os.path.join(self.tmp, "signing", "backed-up"))
        self.patch(sb, "matches_certificate", lambda data: data == b"KEY")
        os.makedirs(os.path.dirname(sb.LEGACY_KEY))
        with open(sb.LEGACY_KEY, "wb") as f:
            f.write(b"KEY")
        with open(sb.LEGACY_MARKER, "w") as f:
            f.write("x\n")

    def run_migrate(self, delete, interactive=True, answer="delete"):
        with contextlib.redirect_stdout(io.StringIO()) as out:
            result = signing_migrate.migrate("Private", delete, interactive, ask=lambda prompt: answer)
        return result, out.getvalue()

    def test_without_the_flag_nothing_changes(self):
        result, _ = self.run_migrate(False)
        self.assertEqual(result, "checked")
        self.assertTrue(os.path.exists(sb.LEGACY_KEY))
        self.assertEqual(self.op.docs, {})

    def test_refuses_without_a_terminal(self):
        with self.assertRaises(RuntimeError):
            self.run_migrate(True, interactive=False)
        self.assertTrue(os.path.exists(sb.LEGACY_KEY))

    def test_stores_reads_back_then_deletes(self):
        result, out = self.run_migrate(True)
        self.assertEqual(result, "deleted")
        self.assertEqual(self.op.docs[("Private", sb.TITLE)], b"KEY")
        self.assertFalse(os.path.exists(sb.LEGACY_KEY))
        self.assertFalse(os.path.exists(sb.LEGACY_MARKER))
        self.assertNotIn("KEY\n", out)

    def test_wrong_answer_keeps_the_key(self):
        result, _ = self.run_migrate(True, answer="no")
        self.assertEqual(result, "kept")
        self.assertTrue(os.path.exists(sb.LEGACY_KEY))

    def test_different_copy_in_the_vault_refuses(self):
        self.op.docs[("Private", sb.TITLE)] = b"OTHER"
        with self.assertRaises(RuntimeError):
            self.run_migrate(True)
        self.assertTrue(os.path.exists(sb.LEGACY_KEY))

    def test_warns_about_copies_in_other_vaults(self):
        self.op.docs[("Shared Family", sb.TITLE)] = b"KEY"
        _, out = self.run_migrate(False)
        self.assertIn("'Shared Family' also has", out)

    def test_key_not_matching_the_certificate_is_left_alone(self):
        with open(sb.LEGACY_KEY, "wb") as f:
            f.write(b"NOT THE KEY")
        with self.assertRaises(RuntimeError):
            self.run_migrate(True)
        self.assertTrue(os.path.exists(sb.LEGACY_KEY))


