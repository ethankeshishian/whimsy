"""Signing: the key comes from 1Password only while signing, nothing secret is
printed or left behind, the vault is explicit, MAR channel IDs and the signed
build-date version, and the one-time migration.

Every key here is a throwaway generated by the test; `op` is a fake.
  python3 -m unittest discover -s whimsy/updater/tests
"""
import contextlib
import glob
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

from _env import ROOT, publish, signing_backup as sb, signing_migrate

OBJ = next(iter(sorted(glob.glob(os.path.join(ROOT, "engine", "obj-*")))), None)
SIGNMAR = OBJ and os.path.join(OBJ, "dist", "bin", "signmar")
MAR = OBJ and os.path.join(OBJ, "dist", "host", "bin", "mar")
HAVE_TOOLS = bool(SIGNMAR and os.path.exists(SIGNMAR) and os.path.exists(MAR)
                  and shutil.which("certutil") and shutil.which("pk12util") and shutil.which("openssl"))


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="whimsy-signing-")
        self.addCleanup(shutil.rmtree, self.tmp, True)

    def patch(self, obj, name, value):
        old = getattr(obj, name)
        setattr(obj, name, value)
        self.addCleanup(setattr, obj, name, old)

    def throwaway_key(self):
        key = os.path.join(self.tmp, "throwaway.pem")
        der = os.path.join(self.tmp, "throwaway.der")
        subprocess.run(["openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-keyout", key, "-outform",
                        "DER", "-out", der, "-days", "1", "-subj", "/CN=Whimsy test"], check=True,
                       capture_output=True)
        with open(key, "rb") as f:
            data = f.read()
        os.remove(key)
        return data, der


class Redaction(Base):
    def test_passwords_never_print(self):
        shown = publish.redact(["openssl", "pkcs12", "-export", "-passout", "pass:hunter2", "-out", "k.p12"])
        self.assertNotIn("hunter2", shown)
        shown = publish.redact(["pk12util", "-i", "k.p12", "-W", "hunter2", "-K", ""])
        self.assertNotIn("hunter2", shown)
        self.assertIn("-passout file:/tmp/p", publish.redact(["x", "-passout", "file:/tmp/p"]))
        self.assertNotIn("hunter2", publish.redact("openssl pkcs12 -passout pass:hunter2"))


