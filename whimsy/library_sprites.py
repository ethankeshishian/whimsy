#!/usr/bin/env python3
"""Draws Whimsy's Library rail icons as 36-frame sprites in Zen's style.

Zen's own Library icons (src/browser/themes/shared/zen-icons/common/library)
are 36 frames of 28x28 side by side, drawn in a 128-unit box with a 7.1-unit
round outline in context-stroke over a context-fill body. Zen plays one once
when its tab is chosen (zen-library-sprite-play, 0.583s, steps(36)) and paints
the body only on the chosen tab. Frame 0 is the resting pose, and every
animation here comes back to it by frame 35, so the end of the play doesn't
jump.

  python3 whimsy/library_sprites.py   # rewrites src/zen/whimsy/content/library/*.svg
"""

import math
import os

FRAMES = 36
SIZE = 28
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "zen", "whimsy", "content", "library")
STROKE = 'stroke="context-stroke" stroke-width="7.1" stroke-linecap="round" stroke-linejoin="round"'
FILL = 'fill="context-fill"'
HEADER = """<!-- This Source Code Form is subject to the terms of the Mozilla Public
   - License, v. 2.0. If a copy of the MPL was not distributed with this
   - file, You can obtain one at http://mozilla.org/MPL/2.0/. -->
<!-- Generated by whimsy/library_sprites.py; edit that, not this. -->
"""


def spring(t, freq=1.15, decay=5.0):
    """A damped spring: 0 at t=0, overshoots once or twice, settles near 0."""
    return math.exp(-decay * t) * math.sin(2 * math.pi * freq * t)


def ease_in_out(t):
    return 0.5 - 0.5 * math.cos(math.pi * max(0.0, min(1.0, t)))


def body(d, extra=""):
    """A filled shape with Zen's outline on top."""
    return f'<path {FILL} d="{d}" {extra}/><path {STROKE} d="{d}" {extra}/>'


def line(d, extra=""):
    return f'<path {STROKE} d="{d}" {extra}/>'


def notes(t):
    # A page that tips as it's picked up while its lines are written in again.
    tilt = -9 * spring(t)
    page = "M36 14h40l24 24v66a10 10 0 0 1-10 10H36a10 10 0 0 1-10-10V24a10 10 0 0 1 10-10Z"
    fold = "M76 14v18a6 6 0 0 0 6 6h18"
    rows = []
    for i, (y, length) in enumerate([(62, 44), (78, 44), (94, 28)]):
        if t == 0:
            k = 1.0
        else:
            k = ease_in_out((t - 0.08 - i * 0.16) / 0.3)
        if k > 0.02:
            rows.append(line(f"M42 {y}h{length * k:.2f}"))
    return f'<g transform="rotate({tilt:.2f} 64 114)">{body(page)}{line(fold)}{"".join(rows)}</g>'


def folders(t):
    # The front of the folder swings open toward you and settles back.
    open_ = max(0.0, spring(t, freq=0.9, decay=4.2))
    back = "M14 34a10 10 0 0 1 10-10h24l10 12h46a10 10 0 0 1 10 10v54a10 10 0 0 1-10 10H24a10 10 0 0 1-10-10Z"
    front = "M14 54h100v46a10 10 0 0 1-10 10H24a10 10 0 0 1-10-10Z"
    sy = 1 - 0.4 * open_
    sk = -18 * open_
    return (f"{body(back)}"
            f'<g transform="translate(0 110) skewX({sk:.2f}) scale(1 {sy:.3f}) translate(0 -110)">{body(front)}</g>')


def screenshots(t):
    # The viewfinder's corners close in on the shot and spring back; the
    # frame inside flashes like a shutter.
    pull = 16 * max(-0.3, spring(t, freq=1.0, decay=4.5))
    corners = [
        ("M18 46V28a10 10 0 0 1 10-10h18", 1, 1),
        ("M82 18h18a10 10 0 0 1 10 10v18", -1, 1),
        ("M110 82v18a10 10 0 0 1-10 10H82", -1, -1),
        ("M46 110H28a10 10 0 0 1-10-10V82", 1, -1),
    ]
    out = "".join(
        line(d, f'transform="translate({dx * pull:.2f} {dy * pull:.2f})"') for d, dx, dy in corners
    )
    flash = 1 - 0.45 * max(0.0, math.sin(math.pi * min(1.0, t / 0.35))) if t else 1
    scale = 0.86 + 0.14 * flash
    shot = "M42 50a8 8 0 0 1 8-8h28a8 8 0 0 1 8 8v28a8 8 0 0 1-8 8H50a8 8 0 0 1-8-8Z"
    return out + f'<g transform="translate(64 64) scale({scale:.3f}) translate(-64 -64)">{body(shot)}</g>'


def meeting(t):
    # The minute hand sweeps once round the clock, which nods as it starts.
    angle = 360 * ease_in_out(t / 0.8) if t else 0
    nod = 1 + 0.06 * spring(t, freq=1.3, decay=6)
    face = "M64 16a48 48 0 1 1 0 96a48 48 0 1 1 0-96Z"
    minute = line("M64 64V34", f'transform="rotate({angle:.2f} 64 64)"')
    hour = line("M64 64l12 8")
    return (f'<g transform="translate(64 64) scale({nod:.3f}) translate(-64 -64)">{body(face)}'
            f"{minute}{hour}</g>")


def archive(t):
    # The way-back arrow pulls back and springs forward, like returning to
    # something put away.
    dx = -18 * spring(t, freq=1.0, decay=4.5)
    arrow = "M108 104V64a28 28 0 0 0-28-28H26"
    head = "M46 14 22 36l24 22"
    return f'<g transform="translate({dx:.2f} 0)">{line(arrow)}{line(head)}</g>'


def playlist(t):
    # The play button presses and the screen answers with a small bounce.
    pop = spring(t, freq=1.2, decay=5.5)
    screen = "M14 34a12 12 0 0 1 12-12h76a12 12 0 0 1 12 12v60a12 12 0 0 1-12 12H26a12 12 0 0 1-12-12Z"
    play = "M56 48v32l26-16Z"
    s = 1 + 0.03 * pop
    p = 1 + 0.32 * pop
    return (f'<g transform="translate(64 64) scale({s:.3f}) translate(-64 -64)">{body(screen)}</g>'
            f'<g transform="translate(66 64) scale({p:.3f}) translate(-66 -64)">'
            f'<path fill="context-stroke" d="{play}"/><path {STROKE} d="{play}"/></g>')


def easels(t):
    # An easel: the canvas rocks on its stand as a stroke is painted across
    # it (Arc's Easels), then settles.
    tilt = -7 * spring(t, freq=1.1, decay=5.0)
    canvas = "M22 18h84a8 8 0 0 1 8 8v52a8 8 0 0 1-8 8H22a8 8 0 0 1-8-8V26a8 8 0 0 1 8-8Z"
    legs = line("M40 86 28 116") + line("M88 86l12 30") + line("M64 86v30")
    if t == 0:
        k = 1.0
    else:
        k = ease_in_out((t - 0.1) / 0.45)
    stroke = line(f"M34 62c10-14 20-14 30 0s20 14 30 0", f'stroke-dasharray="72" stroke-dashoffset="{72 * (1 - k):.2f}"') if k > 0.02 else ""
    return (f'<g transform="rotate({tilt:.2f} 64 116)">{body(canvas)}{stroke}</g>{legs}')


ICONS = {
    "notes": notes,
    "folders": folders,
    "screenshots": screenshots,
    "meeting": meeting,
    "archive": archive,
    "playlist": playlist,
    "easels": easels,
}


def sprite(draw):
    frames = []
    for i in range(FRAMES):
        t = i / (FRAMES - 1)
        x = f' x="{i * SIZE}"' if i else ""
        art = draw(0.0) if i in (0, FRAMES - 1) else draw(t)
        frames.append(f'<svg width="{SIZE}" height="{SIZE}"{x} viewBox="0 0 128 128">{art}</svg>')
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" width="{FRAMES * SIZE}" height="{SIZE}" fill="none">'
            + "".join(frames) + "</svg>\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, draw in ICONS.items():
        with open(os.path.join(OUT, f"library-{name}-sprite.svg"), "w") as f:
            f.write(sprite(draw))


if __name__ == "__main__":
    main()
