"""Icon packs (wave29/icon-sets): generate the Lucide and Phosphor override
stylesheets from Zen's zen-icons/icons.css and the vendored map.json.

Zen's icons.css is never hand-edited (it stays exactly as upstream ships
it), so Whimsy can't add rules there. Instead this reads it as data and
writes two Whimsy-owned stylesheets that `nsIStyleSheetService` loads as a
USER_SHEET on top (WhimsyLook.sys.mjs), one per pack:
  src/zen/whimsy/content/icon-packs/<pack>.css
Each top-level rule block in icons.css that names a `url("name.svg")` is
copied verbatim (selectors, nesting, !important, @media conditions) with
every url() rewritten: a name the pack has points at the Whimsy-owned
vendored file; a name it lacks points at Zen's own file by its absolute
chrome:// URL, so the rule still works when loaded from a different
stylesheet and that one icon simply stays Nucleo (the documented fallback).

    python3 whimsy/tools/iconpacks.py           # regenerate + report
    python3 whimsy/tools/iconpacks.py --check   # regenerate; exit 1 if stale
"""
import json
import os
import re
import sys

ROOT = os.environ.get("WHIMSY_ROOT") or os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PACKS_DIR = os.path.join(ROOT, "src/zen/whimsy/content/icon-packs")
ICONS_CSS = os.path.join(ROOT, "src/browser/themes/shared/zen-icons/icons.css")
NUCLEO_URL = "chrome://browser/skin/zen-icons/{name}.svg"
PACK_URL = "chrome://browser/content/whimsy/icon-packs/{pack}/{name}.svg"

PACKS = ["lucide", "phosphor-fill"]


def _top_level_blocks(css):
    """Yield (selector_and_body_text) for each brace-balanced top-level rule
    block in css, skipping /* ... */ comments. icons.css has no top-level
    @media; nesting only ever appears inside a block, which this keeps."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    depth = 0
    start = None
    for i, ch in enumerate(css):
        if ch == "{":
            if depth == 0:
                start = start if start is not None else _rule_start(css, i)
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0 and start is not None:
                yield css[start:i + 1]
                start = None


def _rule_start(css, brace_pos):
    # Walk back from "{" to just after the previous "}" (or start of file).
    j = css.rfind("}", 0, brace_pos)
    return j + 1


def build(root=ROOT, write=True):
    with open(ICONS_CSS, encoding="utf-8") as f:
        icons_css = f.read()
    with open(os.path.join(PACKS_DIR, "map.json"), encoding="utf-8") as f:
        name_map = json.load(f)

    blocks = list(_top_level_blocks(icons_css))
    pack_sheets = {pack: [] for pack in PACKS}
    fallbacks = set()
    svg_ref = re.compile(r'url\("([\w.-]+)\.svg"\)')

    for block in blocks:
        names = svg_ref.findall(block)
        if not names:
            continue
        for pack in PACKS:
            rewritten = block
            used_pack_file = False
            for name in names:
                hit = name_map.get(name, {}).get(pack)
                if hit:
                    url = PACK_URL.format(pack=pack, name=name)
                    used_pack_file = True
                else:
                    url = NUCLEO_URL.format(name=name)
                    fallbacks.add((name, pack))
                rewritten = rewritten.replace(f'url("{name}.svg")', f'url("{url}")')
            if used_pack_file:
                pack_sheets[pack].append(rewritten.strip())

    header = ("/* Generated by whimsy/tools/iconpacks.py from zen-icons/icons.css "
              "and icon-packs/map.json. Do not hand-edit; re-run the generator. */\n\n")
    outputs = {}
    for pack in PACKS:
        outputs[pack] = header + "\n\n".join(pack_sheets[pack]) + "\n"

    if write:
        for pack in PACKS:
            path = os.path.join(PACKS_DIR, f"{pack}.css")
            with open(path, "w", encoding="utf-8") as f:
                f.write(outputs[pack])

    # Every name in map.json with no hit in either pack is a reviewed
    # fallback (icon-sets.md: "a build check lists those fallbacks").
    all_fallbacks = sorted(
        (name, pack) for name, hits in name_map.items() for pack in PACKS if not hits.get(pack)
    )
    return outputs, all_fallbacks


if __name__ == "__main__":
    outputs, fallbacks = build(write="--check" not in sys.argv)
    if "--check" in sys.argv:
        stale = []
        for pack in PACKS:
            path = os.path.join(PACKS_DIR, f"{pack}.css")
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != outputs[pack]:
                stale.append(pack)
        if stale:
            print("iconpacks: stale, run `python3 whimsy/tools/iconpacks.py` and commit:", ", ".join(stale))
            sys.exit(1)
        print("iconpacks: up to date")
    print(f"iconpacks: {len(fallbacks)} reviewed fallback(s) (name, pack):")
    for name, pack in fallbacks:
        print(f"  {name} ({pack})")
